// Inline the cleaned logo SVGs into a TypeScript module (src/logos.gen.ts).
const fs = require('fs'); const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'logo');
const man = JSON.parse(fs.readFileSync(path.join(dir, 'logo-manifest.json'), 'utf8'));
let out = '// GENERATED by tools/gen_logos_ts.js from assets/logo/*.svg — do not edit.\n';
out += 'interface LogoArt { w: number; h: number; svg: string }\n';
out += 'const LOGO_FILL = \'#6A4937\'; // fill colour baked into the master SVGs; replaced at build time\n';
out += 'const LOGOS: { [id: string]: LogoArt } = {\n';
for (const [id, m] of Object.entries(man)) {
  let svg = fs.readFileSync(path.join(dir, m.file), 'utf8').replace(/\n/g, '');
  // trim decimals to 2 places to keep the bundle small
  svg = svg.replace(/(\d+\.\d)\d+/g, "$1");
  out += `  ${id}: { w: ${m.width}, h: ${m.height}, svg: ${JSON.stringify(svg)} },\n`;
}
out += '};\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'logos.gen.ts'), out);
console.log('logos.gen.ts', out.length, 'bytes');
